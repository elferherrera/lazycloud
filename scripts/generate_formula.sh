#!/usr/bin/env bash
# Regenerate Formula/lazycloud.rb from the elferherrera/lazycloud GitHub
# release. Reads the published .sha256 sidecar files so the checksums
# never come from a local re-download. Exits non-zero when the release is
# missing any expected platform asset.
#
# Usage: scripts/generate_formula.sh [formula_path] [version]
#   formula_path  default Formula/lazycloud.rb
#   version       default: latest release tag from the GitHub API
set -euo pipefail

REPO="elferherrera/lazycloud"
FORMULA_PATH="${1:-Formula/lazycloud.rb}"
API="https://api.github.com/repos/${REPO}/releases/latest"

# Anonymous API calls work but rate-limit quickly; use the GITHUB_TOKEN
# env var when it is present (the workflow passes the token explicitly).
# Single helper instead of an AUTH array: macOS bash 3.2 treats expanding
# an empty array under set -u as an unbound variable.
fetch() {
  if [[ -n "${GITHUB_TOKEN:-}" ]]; then
    curl -fsSL -H "Authorization: Bearer ${GITHUB_TOKEN}" "$@"
  else
    curl -fsSL "$@"
  fi
}

if [[ -n "${2:-}" ]]; then
  TAG="$2"
else
  TAG="$(fetch -H "Accept: application/vnd.github+json" "$API" | sed -n 's/.*"tag_name": *"\([^"]*\)".*/\1/p' | head -1)"
fi
[[ -n "$TAG" ]] || { echo "could not resolve latest release tag" >&2; exit 1; }
VERSION="${TAG#v}"
BASE_URL="https://github.com/${REPO}/releases/download/${TAG}"

checksum() {
  local asset="$1"
  local sha_file="${asset}.sha256"
  # curl -f under pipefail would abort inside the command substitution
  # before the explicit missing-sidecar message below runs, so fetch
  # errors are swallowed here and the empty check reports instead.
  fetch "${BASE_URL}/${sha_file}" 2>/dev/null | awk '{print $1}' || true
}

DARWIN_ARM64_SHA="$(checksum lazycloud-darwin-arm64.tar.gz)"
DARWIN_X86_64_SHA="$(checksum lazycloud-darwin-x86_64.tar.gz)"
LINUX_X86_64_SHA="$(checksum lazycloud-linux-x86_64.tar.gz)"
[[ -n "$DARWIN_ARM64_SHA" && -n "$DARWIN_X86_64_SHA" && -n "$LINUX_X86_64_SHA" ]] || {
  echo "release ${TAG} is missing one or more .sha256 sidecar files" >&2
  exit 1
}

mkdir -p "$(dirname "$FORMULA_PATH")"
cat > "$FORMULA_PATH" <<EOF
# frozen_string_literal: true

# Generated by scripts/generate_formula.sh in this repo. Do not edit by
# hand; regenerated by the elferherrera/lazycloud release workflow.
class Lazycloud < Formula
  desc "Terminal UI for browsing Google Cloud Platform resources"
  homepage "https://github.com/${REPO}"
  version "${VERSION}"

  on_macos do
    on_arm do
      url "${BASE_URL}/lazycloud-darwin-arm64.tar.gz"
      sha256 "${DARWIN_ARM64_SHA}"

      def install
        bin.install "lazycloud"
      end
    end
    on_intel do
      url "${BASE_URL}/lazycloud-darwin-x86_64.tar.gz"
      sha256 "${DARWIN_X86_64_SHA}"

      def install
        bin.install "lazycloud"
      end
    end
  end

  on_linux do
    on_intel do
      url "${BASE_URL}/lazycloud-linux-x86_64.tar.gz"
      sha256 "${LINUX_X86_64_SHA}"

      def install
        bin.install "lazycloud"
      end
    end
  end

  def caveats
    <<~EOS
      lazycloud is a terminal UI: run it from a real terminal, not from a
      script. Requires an authenticated gcloud CLI; the workloads view
      additionally requires kubectl on your PATH.

      Configuration and cache live under ~/.config/lazycloud/.
    EOS
  end

  test do
    assert_equal "v#{version}", shell_output("#{bin}/lazycloud --version").strip
  end
end
EOF
ruby -c "$FORMULA_PATH" >/dev/null
echo "regenerated ${FORMULA_PATH} at ${VERSION}"
